@dataclass(frozen=True)
class Language:
    name: str
    extensions: tuple
    analyze: object            # text -> (kinds, syntax_problem or None); raises LexError
    line_prefixes: tuple
    block_open: str
    block_close: str
    quote_chars: str           # quotes that must never be classified as code
    looks_like_code: object
    equivalent: object = None  # (old, new) -> problem or None; extra semantic check
    brace_check: bool = False
    tab_check: bool = False
    duplicates: bool = False


LANGUAGES = {
    'cs': Language('C#', ('.cs',), lambda t: (CSharpLexer(t).run(), None), ('//',), '/*', '*/', '"\'',
                   looks_like_c_code, brace_check=True, tab_check=True, duplicates=True),
    'ps1': Language('PowerShell', ('.ps1', '.psm1'), analyze_powershell, ('#',), '<#', '#>', '',
                    looks_like_ps_code, brace_check=True),
    'xaml': Language('XAML / Avalonia AXAML', ('.xaml', '.axaml'), lambda t: (lex_xaml(t), xml_check(t)), (), '<!--', '-->', '',
                     looks_like_xaml_code, equivalent=xml_equivalent),
    'xml': Language('XML project/manifest/config', ('.csproj', '.props', '.targets', '.xml', '.manifest', '.config'),
                    lambda t: (lex_xaml(t), xml_check(t)), (), '<!--', '-->', '',
                    looks_like_xaml_code, equivalent=xml_equivalent),
    'js': Language('JavaScript', ('.js',), lambda t: (JsLexer(t).run(), node_check(t)), ('//',), '/*', '*/', '"\'`',
                   looks_like_c_code, brace_check=True),
}


def language_for(path):
    ext = path.suffix.lower()
    return next((lang for lang in LANGUAGES.values() if ext in lang.extensions), None)


def lex(text):
    return CSharpLexer(text).run()


