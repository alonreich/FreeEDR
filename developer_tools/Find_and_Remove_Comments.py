class JsLexer:
    """Classifies JavaScript: // and /* */ comments (/** */ = doc), '...' and "..." strings, `...`
    templates with nested ${...} holes, and regex literals."""

    REGEX_AFTER_WORDS = {'return', 'typeof', 'instanceof', 'in', 'of', 'new', 'delete', 'void', 'throw',
                         'case', 'do', 'else', 'yield', 'await'}
    REGEX_AFTER_CHARS = set('(,=:[!&|?{};+-*%<>~^')

    def __init__(self, text):
        self.s = text
        self.n = len(text)
        self.kinds = bytearray(self.n)

    def mark(self, kind, a, b):
        if b > a:
            self.kinds[a:b] = bytes([kind]) * (b - a)

    def run(self):
        end = self.code(0, hole=False)
        if end != self.n:
            raise LexError(f'unbalanced closing brace in template hole at offset {end}')
        return self.kinds

    def code(self, i, hole):
        s, n = self.s, self.n
        depth, prev, prev_word = 0, None, ''
        while i < n:
            c = s[i]
            if c.isspace():
                i += 1
                continue
            if c == '/' and i + 1 < n and s[i + 1] == '/':
                j = s.find('\n', i)
                j = n if j < 0 else j
                if j > i and s[j - 1] == '\r':
                    j -= 1
                self.mark(LCOM, i, j)
                i = j
                continue
            if c == '/' and i + 1 < n and s[i + 1] == '*':
                j = s.find('*/', i + 2)
                if j < 0:
                    raise LexError(f'unterminated block comment at offset {i}')
                is_doc = s.startswith('/**', i) and not s.startswith('/**/', i)
                self.mark(DOC if is_doc else BCOM, i, j + 2)
                i = j + 2
                continue
            if c in '"\'':
                i = self.string(i, c)
                prev, prev_word = 'a', ''
                continue
            if c == '`':
                i = self.template(i)
                prev, prev_word = 'a', ''
                continue
            if c == '/':
                if prev is None or prev in self.REGEX_AFTER_CHARS or (prev == 'a' and prev_word in self.REGEX_AFTER_WORDS):
                    i = self.regex(i)
                    prev, prev_word = 'a', ''
                    continue
                prev, prev_word = '/', ''
                i += 1
                continue
            if c.isalnum() or c in '_$#':
                j = i + 1
                while j < n and (s[j].isalnum() or s[j] in '_$'):
                    j += 1
                prev, prev_word = 'a', s[i:j]
                i = j
                continue
            if hole:
                if c == '{':
                    depth += 1
                elif c == '}':
                    if depth == 0:
                        return i + 1
                    depth -= 1
            prev, prev_word = c, ''
            i += 1
        if hole:
            raise LexError('unterminated template hole')
        return i

    def string(self, i, quote):
        s, n = self.s, self.n
        j = i + 1
        while j < n:
            c = s[j]
            if c == '\\':
                j += 3 if s.startswith('\r\n', j + 1) else 2
                continue
            if c == quote:
                self.mark(STR, i, j + 1)
                return j + 1
            if c == '\n':
                raise LexError(f'newline in string literal at offset {i}')
            j += 1
        raise LexError(f'unterminated string literal at offset {i}')

    def template(self, i):
        s, n = self.s, self.n
        seg, j = i, i + 1
        while j < n:
            c = s[j]
            if c == '\\':
                j += 2
                continue
            if c == '`':
                self.mark(STR, seg, j + 1)
                return j + 1
            if c == '$' and j + 1 < n and s[j + 1] == '{':
                self.mark(STR, seg, j + 2)
                k = self.code(j + 2, hole=True)
                seg, j = k - 1, k
                continue
            j += 1
        raise LexError(f'unterminated template literal at offset {i}')

    def regex(self, i):
        s, n = self.s, self.n
        j, in_class = i + 1, False
        while j < n:
            c = s[j]
            if c == '\\':
                j += 2
                continue
            if c in '\r\n':
                raise LexError(f'unterminated regex literal at offset {i}')
            if c == '[':
                in_class = True
            elif c == ']':
                in_class = False
            elif c == '/' and not in_class:
                j += 1
                while j < n and s[j].isalpha():
                    j += 1
                self.mark(STR, i, j)
                return j
            j += 1
        raise LexError(f'unterminated regex literal at offset {i}')


