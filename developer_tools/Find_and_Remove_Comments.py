def run_with_temp_file(text, suffix, command_builder):
    """Writes text to a NEW temp file in the system temp folder (never the repository), runs the
    command and removes only that temp file."""
    handle, temp_path = tempfile.mkstemp(prefix='freeedr-clean-', suffix=suffix)
    try:
        with os.fdopen(handle, 'w', encoding='utf-8', newline='') as f:
            f.write(text)
        return subprocess.run(command_builder(temp_path), capture_output=True, timeout=EXTERNAL_CHECK_TIMEOUT)
    finally:
        try:
            os.remove(temp_path)
        except OSError:
            pass


def node_check(text):
    node = shutil.which('node')
    if node is None:
        return 'node.js not found; JavaScript needs `node --check` verification'
    try:
        result = run_with_temp_file(text, '.js', lambda p: [node, '--check', p])
    except (OSError, subprocess.SubprocessError) as exc:
        return f'node --check could not run ({type(exc).__name__})'
    if result.returncode != 0:
        lines = result.stderr.decode('utf-8', errors='replace').strip().splitlines()
        detail = next((l for l in lines if 'Error' in l), lines[-1] if lines else 'syntax error')
        return 'node --check failed: ' + detail.strip()
    return None


PS_TOKENIZER = (
    "$ErrorActionPreference='Stop';"
    "$t=[IO.File]::ReadAllText('{path}',[Text.UTF8Encoding]::new($false));"
    "$tk=$null;$er=$null;"
    "[void][System.Management.Automation.Language.Parser]::ParseInput($t,[ref]$tk,[ref]$er);"
    "$o=@(foreach($k in $tk){{$n=[string]$k.Kind;"
    "if($n -eq 'Comment' -or $n -like 'String*' -or $n -like 'HereString*'){{,@($n,$k.Extent.StartOffset,$k.Extent.EndOffset)}}}});"
    "$e=@(foreach($x in $er){{[string]$x.Extent.StartLineNumber+': '+$x.Message}});"
    "ConvertTo-Json -Compress -Depth 4 -InputObject @{{errors=$e;tokens=$o}}"
)
PS_HELP_RE = re.compile(r'(?im)^\s*\.(?:SYNOPSIS|DESCRIPTION|PARAMETER|EXAMPLE|NOTES|OUTPUTS|INPUTS|LINK)\b')


def utf16_to_index(text):
    """Map from UTF-16 code-unit offsets (what .NET reports) to Python string indexes."""
    if all(ord(ch) < 0x10000 for ch in text):
        return lambda off: off
    table = []
    for idx, ch in enumerate(text):
        table.append(idx)
        if ord(ch) >= 0x10000:
            table.append(idx)  # second code unit of a surrogate pair
    table.append(len(text))
    return lambda off: table[min(off, len(table) - 1)]


def analyze_powershell(text):
    shell = shutil.which('powershell') or shutil.which('pwsh')
    if shell is None:
        raise LexError('PowerShell not found; PowerShell files need its parser for lexing')
    try:
        result = run_with_temp_file(text, '.ps1', lambda p: [
            shell, '-NoProfile', '-NonInteractive', '-Command', PS_TOKENIZER.format(path=p.replace("'", "''"))])
        data = json.loads(result.stdout.decode('utf-8', errors='strict') or 'null')
    except (OSError, subprocess.SubprocessError, ValueError, UnicodeError) as exc:
        raise LexError(f'PowerShell tokenizer failed ({type(exc).__name__})')
    if result.returncode != 0 or not isinstance(data, dict):
        raise LexError('PowerShell tokenizer failed: ' + result.stderr.decode('utf-8', errors='replace').strip()[:200])
    to_index = utf16_to_index(text)
    kinds = bytearray(len(text))
    for token in data.get('tokens') or []:
        name, a, b = token[0], to_index(token[1]), to_index(token[2])
        if name == 'Comment':
            body = text[a:b]
            kind = (DOC if PS_HELP_RE.search(body) else BCOM) if body.startswith('<#') else LCOM
        else:
            kind = STR
        kinds[a:b] = bytes([kind]) * (b - a)
    errors = data.get('errors') or []
    return kinds, ('PowerShell parse errors: ' + '; '.join(errors[:3])) if errors else None


def xml_check(text):
    try:
        ET.fromstring(text)
    except ET.ParseError as exc:
        return f'XML parse failed: {exc}'
    return None


def xml_shape(element):
    """Comment-free element tree. Whitespace-only text is formatting and compares as empty; any
    text with content compares EXACTLY."""
    def text(value):
        return '' if value is None or not value.strip() else value
    return (element.tag, sorted(element.attrib.items()), text(element.text), text(element.tail),
            [xml_shape(child) for child in element])


def xml_equivalent(old_text, new_text):
    try:
        same = xml_shape(ET.fromstring(old_text)) == xml_shape(ET.fromstring(new_text))
    except ET.ParseError as exc:
        return f'XML comparison failed: {exc}'
    return None if same else 'XML content (without comments) would change'


