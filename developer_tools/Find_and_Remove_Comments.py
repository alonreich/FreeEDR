class CSharpLexer:
    """Classifies every character of a C# source file into a token kind.

    Handles // and /* */ comments, /// and /** */ doc comments, preprocessor lines, char literals,
    regular, verbatim (@""), interpolated ($"", $@"", @$"") and raw ($$\"\"\"...\"\"\") strings, including
    interpolation holes that contain nested strings. Raises LexError on anything unterminated so that
    the caller can refuse to edit a file it does not fully understand.
    """

    STRING_START_RE = re.compile(r'(\$+@?|@\$+|@)?("{3,}|")')

    def __init__(self, text):
        self.s = text
        self.n = len(text)
        self.kinds = bytearray(self.n)  # 0 == CODE

    def mark(self, kind, a, b):
        if b > a:
            self.kinds[a:b] = bytes([kind]) * (b - a)

    def run(self):
        end = self.code(0, hole=False)
        if end != self.n:
            raise LexError(f'unbalanced closing brace in interpolation at offset {end}')
        return self.kinds

    def at_line_start(self, i):
        j = i - 1
        while j >= 0 and self.s[j] in ' \t':
            j -= 1
        return j < 0 or self.s[j] == '\n'

    def code(self, i, hole):
        s, n = self.s, self.n
        depth = 0
        while i < n:
            c = s[i]
            if c == '/' and i + 1 < n and s[i + 1] == '/':
                j = s.find('\n', i)
                j = n if j < 0 else j
                if j > i and s[j - 1] == '\r':
                    j -= 1
                is_doc = s.startswith('///', i) and not s.startswith('////', i)
                self.mark(DOC if is_doc else LCOM, i, j)
                i = j
                continue
            if c == '/' and i + 1 < n and s[i + 1] == '*':
                j = s.find('*/', i + 2)
                if j < 0:
                    raise LexError(f'unterminated block comment at offset {i}')
                is_doc = s.startswith('/**', i) and not s.startswith('/**/', i)
                self.mark(DOC if is_doc else BCOM, i, j + 2)
                i = j + 2
                continue
            if c == '#' and not hole and self.at_line_start(i):
                j = s.find('\n', i)
                j = n if j < 0 else j
                if j > i and s[j - 1] == '\r':
                    j -= 1
                self.mark(PRE, i, j)
                i = j
                continue
            if c == "'":
                i = self.char_literal(i)
                continue
            if c in '"$@':
                m = self.STRING_START_RE.match(s, i)
                if m and not (i > 0 and (s[i - 1].isalnum() or s[i - 1] == '_') and c != '"'):
                    i = self.string_literal(i, m)
                    continue
            if hole:
                if c == '{':
                    depth += 1
                elif c == '}':
                    if depth == 0:
                        return i + 1
                    depth -= 1
            i += 1
        if hole:
            raise LexError('unterminated interpolation hole')
        return i

    def char_literal(self, i):
        s, n = self.s, self.n
        j = i + 1
        while j < n and s[j] != "'":
            if s[j] == '\\':
                j += 1
            if j < n and s[j] == '\n':
                raise LexError(f'unterminated char literal at offset {i}')
            j += 1
        if j >= n:
            raise LexError(f'unterminated char literal at offset {i}')
        self.mark(CHR, i, j + 1)
        return j + 1

    def string_literal(self, i, m):
        prefix, quotes = m.group(1) or '', m.group(2)
        dollars = prefix.count('$')
        verbatim = '@' in prefix
        start = i
        i = m.end()
        if len(quotes) >= 3 and not verbatim:
            return self.raw_string(start, i, len(quotes), dollars)
        if len(quotes) >= 3 and verbatim:
            i = m.start(2) + 1
        elif len(quotes) == 2:
            i = m.start(2) + 1
        return self.quoted_string(start, i, verbatim, dollars > 0)

    def quoted_string(self, start, i, verbatim, interpolated):
        s, n = self.s, self.n
        seg = start
        while i < n:
            c = s[i]
            if c == '\\' and not verbatim:
                i += 2
                continue
            if c == '"':
                if verbatim and i + 1 < n and s[i + 1] == '"':
                    i += 2
                    continue
                self.mark(STR, seg, i + 1)
                return i + 1
            if c == '\n' and not verbatim:
                raise LexError(f'newline in regular string literal at offset {start}')
            if interpolated and c == '{':
                if i + 1 < n and s[i + 1] == '{':
                    i += 2
                    continue
                self.mark(STR, seg, i + 1)
                i = self.code(i + 1, hole=True)
                seg = i - 1  # closing brace belongs to the string
                continue
            if interpolated and c == '}' and i + 1 < n and s[i + 1] == '}':
                i += 2
                continue
            i += 1
        raise LexError(f'unterminated string literal at offset {start}')

    def raw_string(self, start, i, quote_count, dollars):
        s, n = self.s, self.n
        closing = '"' * quote_count
        seg = start
        while i < n:
            if s.startswith(closing, i):
                j = i
                while j < n and s[j] == '"':
                    j += 1
                self.mark(STR, seg, j)
                return j
            if dollars and s[i] == '{':
                j = i
                while j < n and s[j] == '{':
                    j += 1
                run = j - i
                if run >= dollars:
                    self.mark(STR, seg, j)
                    k = self.code(j, hole=True)
                    for _ in range(dollars - 1):
                        if k < n and s[k] == '}':
                            k += 1
                        else:
                            raise LexError(f'raw interpolation hole not closed with {dollars} braces at {k}')
                    seg = k - dollars
                    i = k
                    continue
                i = j
                continue
            i += 1
        raise LexError(f'unterminated raw string literal at offset {start}')


