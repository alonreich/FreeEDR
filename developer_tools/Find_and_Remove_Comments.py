# XAML / AXAML / XML LEXER
# ══════════════════════════════════════════════════════════════════════════════════════════
def lex_xaml(text):
    """<!-- --> = block comment, <![CDATA[ ]]> and quoted attribute values = string, <? ?> = preprocessor."""
    n = len(text)
    kinds = bytearray(n)

    def mark(kind, a, b):
        kinds[a:b] = bytes([kind]) * (b - a)

    i, in_tag = 0, False
    while i < n:
        for opener, closer, kind in (('<!--', '-->', BCOM), ('<![CDATA[', ']]>', STR), ('<?', '?>', PRE)):
            if not in_tag and text.startswith(opener, i):
                j = text.find(closer, i + len(opener))
                if j < 0:
                    raise LexError(f'unterminated {opener} at offset {i}')
                mark(kind, i, j + len(closer))
                i = j + len(closer)
                break
        else:
            c = text[i]
            if not in_tag and c == '<':
                in_tag = True
            elif in_tag and c in '"\'':
                j = text.find(c, i + 1)
                if j < 0:
                    raise LexError(f'unterminated attribute value at offset {i}')
                mark(STR, i, j + 1)
                i = j + 1
                continue
            elif in_tag and c == '>':
                in_tag = False
            i += 1
    return kinds


