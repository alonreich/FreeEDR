def split_lines(text):
    """Returns (start, content_end, line_end) per line; content excludes \\r\\n / \\n."""
    lines, pos, n = [], 0, len(text)
    while pos < n:
        nl = text.find('\n', pos)
        end = n if nl < 0 else nl + 1
        content_end = nl if nl >= 0 else n
        if content_end > pos and text[content_end - 1] == '\r':
            content_end -= 1
        lines.append((pos, content_end, end))
        pos = end
    return lines


def protection_reason(comment_text):
    for reason, pattern in PROTECT_RULES:
        if pattern.search(comment_text):
            return reason
    return None


def comment_body(line, lang):
    s = line.strip()
    for prefix in lang.line_prefixes:
        if s.startswith(prefix):
            return s[len(prefix):].strip()
    if s.startswith(lang.block_open):
        s = s[len(lang.block_open):]
    if s.endswith(lang.block_close):
        s = s[:-len(lang.block_close)]
    return s.strip().lstrip('*').strip()


def junk_kind(block_lines, lang):
    """'COMMENTED-OUT CODE' / 'EMPTY COMMENT' when the whole block is knowledge-free, else None."""
    bodies = [comment_body(l, lang) for l in block_lines]
    if all(not b for b in bodies):
        return 'EMPTY COMMENT'
    if all((not b) or lang.looks_like_code(b) for b in bodies):
        return 'COMMENTED-OUT CODE'
    return None


def load_sentinels(root):
    tags = defaultdict(set)
    manifest = root / 'build' / 'sentinels.txt'
    if manifest.exists():
        for raw in manifest.read_text(encoding='utf-8-sig').splitlines():
            line = raw.strip()
            if not line or line.startswith('#') or '=' not in line:
                continue
            tag, path = (part.strip() for part in line.split('=', 1))
            tags[path.lower()].add(tag)
    return tags


def token_stream(text, kinds):
    """Everything except plain comments, with code whitespace normalised. Used to prove that an
    edit changed nothing but comments and blank lines."""
    out, cur_kind, buf = [], None, []
    for i, ch in enumerate(text):
        k = kinds[i]
        if k in COMMENT_KINDS:
            continue
        if k != cur_kind:
            if buf:
                out.append((cur_kind, ''.join(buf)))
            cur_kind, buf = k, []
        buf.append(ch)
    if buf:
        out.append((cur_kind, ''.join(buf)))
    merged = []
    for k, t in out:
        if merged and merged[-1][0] == k == CODE:
            merged[-1] = (CODE, merged[-1][1] + ' ' + t)
        else:
            merged.append((k, t))
    result = []
    for k, t in merged:
        if k == CODE:
            t = re.sub(r'\s+', ' ', t).strip()
            if not t:
                continue
        elif k == DOC:
            t = t.strip()
        result.append((k, t))
    return result


def plan_file(path, root, sentinels, aggressive=False):
    """Returns a dict describing the planned edits for one file, or the reason it is skipped."""
    rel = path.relative_to(root).as_posix()
    lang = language_for(path)
    info = {'path': path, 'rel': rel, 'lang': lang, 'items': [], 'protected': [], 'skip': None,
            'new_bytes': None, 'syntax_problem': None}
    raw = path.read_bytes()
    # In FreeEDR, all *.ps1/*.psm1 files must have a UTF-8 BOM.
    bom = raw.startswith(b'\xef\xbb\xbf') or path.suffix.lower() in ('.ps1', '.psm1')
    try:
        text = raw[3 if raw.startswith(b'\xef\xbb\xbf') else 0:].decode('utf-8', errors='strict')
    except UnicodeError:
        info['skip'] = 'not valid UTF-8; left untouched'
        return info
    try:
        kinds, syntax_problem = lang.analyze(text)
    except LexError as exc:
        info['skip'] = f'lexer could not fully parse ({exc}); left untouched'
        return info
    info['syntax_problem'] = syntax_problem
    if lang.quote_chars:
        stray = next((i for i, ch in enumerate(text) if ch in lang.quote_chars and kinds[i] == CODE), None)
        if stray is not None:
            info['skip'] = f'lexer sanity check failed (quote outside a literal at line {text.count(chr(10), 0, stray) + 1}); left untouched'
            return info
    info['text'], info['kinds'], info['bom'] = text, kinds, bom
    lines = split_lines(text)
    line_starters = lang.line_prefixes + (lang.block_open,)

    def nonws_kinds(idx):
        a, b, _ = lines[idx]
        return {kinds[j] for j in range(a, b) if not text[j].isspace()}

    def is_blank_code_line(idx):
        a, b, e = lines[idx]
        if text[a:b].strip():
            return False
        probe = a if a < len(text) else len(text) - 1
        return kinds[probe] == CODE if a < e else True

    line_kinds = [nonws_kinds(i) for i in range(len(lines))]
    full_comment = [bool(k) and k <= COMMENT_KINDS for k in line_kinds]
    actions = {}
    i = 0
    while i < len(lines):
        if not full_comment[i]:
            i += 1
            continue
        j = i
        while j + 1 < len(lines) and full_comment[j + 1]:
            j += 1
        a, b = lines[i][0], lines[j][1]
        first_char = next(k for k in range(lines[i][0], lines[i][1]) if not text[k].isspace())
        starts_clean = text.startswith(line_starters, first_char)
        ends_clean = True
        last = lines[j]
        tail = text[last[0]:last[1]].rstrip()
        if kinds[last[0] + len(tail) - 1] == BCOM and not tail.endswith(lang.block_close):
            ends_clean = False
        block_text = text[a:b]
        reason = protection_reason(block_text)
        prev_code = next((k for k in range(i - 1, -1, -1) if text[lines[k][0]:lines[k][1]].strip()), None)
        next_code = next((k for k in range(j + 1, len(lines)) if text[lines[k][0]:lines[k][1]].strip()), None)
        if (reason is None and prev_code is not None and next_code is not None
                and text[lines[prev_code][0]:lines[prev_code][1]].rstrip().endswith('{')
                and text[lines[next_code][0]:lines[next_code][1]].lstrip().startswith('}')):
            reason = 'explains an intentionally empty block'
        if not (starts_clean and ends_clean):
            reason = reason or 'part of a block comment that shares a line with code'
        block_lines = [text[lines[k][0]:lines[k][1]] for k in range(i, j + 1)]
        kind_label = junk_kind(block_lines, lang)
        if reason is None and not aggressive and kind_label is None:
            reason = EXPLANATORY_KEPT
        if reason:
            info['protected'].append({'line': i + 1, 'end': j + 1, 'reason': reason,
                                      'content': text[lines[i][0]:lines[i][1]].strip()})
        else:
            label = kind_label or ('COMMENT' if j == i else 'COMMENT BLOCK')
            for k in range(i, j + 1):
                actions[k] = {'action': 'DELETE', 'type': label,
                              'line': k + 1, 'content': text[lines[k][0]:lines[k][1]].strip()}
        i = j + 1

    # Trailing comments after code on the same line: `code; // note` -> `code;`
    for idx, (a, b, e) in enumerate(lines):
        if idx in actions or full_comment[idx] or not line_kinds[idx]:
            continue
        k = b - 1
        while k >= a and text[k].isspace():
            k -= 1
        if k < a or kinds[k] not in COMMENT_KINDS:
            continue
        kind = kinds[k]
        start = k
        while start > a and kinds[start - 1] == kind:
            start -= 1
        if (start == a or kinds[start] != kind
                or (kind == BCOM and not text.startswith(lang.block_open, start))
                or (kind == LCOM and not text.startswith(lang.line_prefixes, start))):
            continue
        comment = text[start:k + 1]
        code_part = text[a:start].rstrip(' \t')
        if not code_part.strip():
            continue
        reason = protection_reason(comment)
        trailing_label = junk_kind([comment], lang)
        if reason is None and not aggressive and trailing_label is None:
            reason = EXPLANATORY_KEPT
        if reason:
            info['protected'].append({'line': idx + 1, 'end': idx + 1, 'reason': reason, 'content': comment})
            continue
        actions[idx] = {'action': 'EDIT', 'type': 'INLINE ' + (trailing_label or 'COMMENT'), 'line': idx + 1,
                        'content': f'Rem: {comment}', 'new_content': code_part + text[b:e]}

    # Excessive blank lines (outside strings / comments), evaluated after the deletions above.
    run, prev_deleted_comment = 0, False
    for idx in range(len(lines)):
        if idx in actions and actions[idx]['action'] == 'DELETE':
            prev_deleted_comment = True
            continue
        if is_blank_code_line(idx):
            run += 1
            limit = 1 if prev_deleted_comment and run > 1 else MAX_BLANK_RUN
            if run > limit:
                actions[idx] = {'action': 'DELETE', 'type': 'EXCESSIVE EMPTY', 'line': idx + 1,
                                'content': '<Excessive Empty>'}
        else:
            run, prev_deleted_comment = 0, False

    if not actions:
        return info
    if syntax_problem:
        info['skip'] = f'original fails its syntax check ({syntax_problem}); left untouched'
        return info
    out = []
    for idx, (a, b, e) in enumerate(lines):
        act = actions.get(idx)
        if act is None:
            out.append(text[a:e])
        elif act['action'] == 'EDIT':
            out.append(act['new_content'])
    new_text = ''.join(out)
    problem = verify_edit(lang, text, kinds, new_text, sentinels.get(rel.lower(), set()))
    if problem:
        info['skip'] = 'self-verification failed (' + problem + '); left untouched'
        return info
    info['items'] = [actions[k] for k in sorted(actions)]
    info['new_text'] = new_text
    info['new_bytes'] = (b'\xef\xbb\xbf' if bom else b'') + new_text.encode('utf-8')
    return info


def verify_edit(lang, old_text, old_kinds, new_text, required_tags):
    try:
        new_kinds, new_problem = lang.analyze(new_text)
    except LexError as exc:
        return f'edited text no longer lexes: {exc}'
    if new_problem:
        return f'edited text fails its syntax check: {new_problem}'
    if token_stream(old_text, old_kinds) != token_stream(new_text, new_kinds):
        return 'code/string/doc tokens would change'
    if lang.equivalent is not None:
        problem = lang.equivalent(old_text, new_text)
        if problem:
            return problem
    for tag in required_tags:
        if tag not in new_text:
            return f'sentinel tag {tag} would disappear'
    if Counter(TAG_RE.findall(old_text)) != Counter(TAG_RE.findall(new_text)):
        return 'engineering tag count would change'
    old_has_crlf = '\r\n' in old_text
    old_has_lf_only = '\n' in old_text.replace('\r\n', '')
    if old_has_crlf != old_has_lf_only:
        if '\r\n' in new_text and '\n' in new_text.replace('\r\n', ''):
            return 'line endings would become mixed'
    return None


# ── C# conditional compilation (#if / #elif / #else / #endif) ─────────────────────────────
PP_COND_RE = re.compile(r'#\s*(if|elif|else|endif)\b')


def conditional_contexts(text, kinds, lines):
    contexts, stack, next_id = [], [], 0
    for a, b, _ in lines:
        first = a
        while first < b and text[first].isspace():
            first += 1
        if first < b and kinds[first] == PRE:
            m = PP_COND_RE.match(text, first)
            if m:
                kw = m.group(1)
                if kw == 'if':
                    stack.append([next_id, 0])
                    next_id += 1
                elif kw in ('elif', 'else') and stack:
                    stack[-1][1] += 1
                elif kw == 'endif' and stack:
                    stack.pop()
        contexts.append(tuple((f[0], f[1]) for f in stack))
    return contexts


def is_secondary_branch(context):
    return any(branch > 0 for _, branch in context)


def contexts_compatible(c1, c2):
    d1 = dict(c1)
    return all(d1[k] == v for k, v in c2 if k in d1)


def code_only(text, kinds, contexts=None):
    chars = [ch if (kinds[i] == CODE or ch == '\n') else ' ' for i, ch in enumerate(text)]
    if contexts:
        for (a, b, _), ctx in zip(split_lines(text), contexts):
            if is_secondary_branch(ctx):
                chars[a:b] = ' ' * (b - a)
    return ''.join(chars)


def check_syntax(info):
    text, kinds, lang = info.get('text'), info.get('kinds'), info.get('lang')
    if text is None:
        return info['skip']
    issues = []
    if info.get('syntax_problem'):
        issues.append(info['syntax_problem'])
    if lang.brace_check:
        contexts = conditional_contexts(text, kinds, split_lines(text)) if lang.duplicates else None
        code = code_only(text, kinds, contexts)
        if lang.tab_check and '\t' in code:
            issues.append('Contains tabs (outside strings)')
        if code.count('{') != code.count('}'):
            issues.append(f"Mismatched braces in code ({code.count('{')} '{{' vs {code.count('}')} '}}')")
        if code.count('(') != code.count(')'):
            issues.append(f"Mismatched parentheses in code ({code.count('(')} vs {code.count(')')})")
    return '; '.join(issues) or None


MEMBER_MODIFIERS = (r'(?:(?:public|private|protected|internal|static|virtual|override|async|sealed|partial|abstract|'
                    r'readonly|unsafe|new|extern|const|event|volatile|required|file)\s+)*')
DECL_RE = re.compile(
    r'^\s*' + MEMBER_MODIFIERS +
    r'(?P<kw>(?:record\s+)?(?:class|struct)|record|interface|enum|(?:delegate\s+)?'
    r'[\w.]+(?:<[^;=(){}]*>)?(?:\?|\[[,\s]*\])*)'
    r'\s+(?P<name>[A-Za-z_]\w*)\s*(?P<rest>[(<{:;=].*)?$')
TYPE_KW_RE = re.compile(r'^(?:record\s+)?(?:class|struct)$|^(?:record|interface|enum)$')
NOT_A_TYPE = {'return', 'new', 'throw', 'await', 'using', 'else', 'case', 'goto', 'yield', 'namespace', 'var',
              'public', 'private', 'protected', 'internal', 'static', 'virtual', 'override', 'async', 'sealed',
              'partial', 'abstract', 'readonly', 'unsafe', 'extern', 'const', 'event', 'volatile', 'required', 'file'}


def parameter_list(rest):
    start = rest.find('(')
    if start < 0:
        return ''
    depth = 0
    for k in range(start, len(rest)):
        depth += {'(': 1, ')': -1}.get(rest[k], 0)
        if depth == 0:
            return re.sub(r'\s+', ' ', rest[start:k + 1])
    return re.sub(r'\s+', ' ', rest[start:]) + '...'


def analyze_duplicates(info):
    text, kinds, lang = info.get('text'), info.get('kinds'), info.get('lang')
    if text is None or kinds is None or not lang.duplicates:
        return []
    lines = split_lines(text)
    contexts = conditional_contexts(text, kinds, lines)
    found = defaultdict(list)
    current_ns = 'GLOBAL'
    types = []
    depth = 0
    for idx, (a, b, e) in enumerate(lines):
        secondary = is_secondary_branch(contexts[idx])
        while types and types[-1][2] and depth < types[-1][1]:
            types.pop()
        line = text[a:b]
        stripped = line.strip()
        first_non_ws = a
        while first_non_ws < b and text[first_non_ws].isspace():
            first_non_ws += 1
        if stripped and first_non_ws < b and kinds[first_non_ws] == CODE:
            match = DECL_RE.match(line)
            if stripped.startswith('namespace ') and len(stripped.split()) > 1:
                current_ns = stripped.split()[1].rstrip(';{')
            elif match and match['kw'] not in NOT_A_TYPE:
                kw, name = re.sub(r'\s+', ' ', match['kw']), match['name']
                counted = types[-1][1] == depth if types else TYPE_KW_RE.match(kw) is not None
                if counted:
                    scope = '.'.join([current_ns] + [t[0] for t in types])
                    found[(scope, kw, name + parameter_list(match['rest'] or ''))].append((idx + 1, contexts[idx]))
                if TYPE_KW_RE.match(kw) and not secondary:
                    k = a
                    while k < len(text) and not (kinds[k] == CODE and text[k] in '{;'):
                        k += 1
                    if k < len(text) and text[k] == '{':
                        types.append([name, depth + 1, False])
        if not secondary:
            for k in range(a, b):
                if kinds[k] == CODE:
                    if text[k] == '{':
                        depth += 1
                    elif text[k] == '}':
                        depth -= 1
        if types and depth >= types[-1][1]:
            types[-1][2] = True
    duplicates = []
    for (scope, kw, sig), occurrences in found.items():
        clashing = sorted({line for i, (line, ctx) in enumerate(occurrences)
                           for other_line, other_ctx in occurrences[i + 1:]
                           if contexts_compatible(ctx, other_ctx)
                           for line in (line, other_line)})
        if clashing:
            duplicates.append([info['rel'], scope, kw, sig, ", ".join(map(str, clashing))])
    return duplicates


