# FreeEDR comment cleaner (developer tool, never built, packed or installed; not in $ProjectFiles).
# Languages: C# (.cs), PowerShell (.ps1, .psm1), Avalonia XAML / XAML (.axaml, .xaml),
# XML project/manifest/config (.csproj, .props, .targets, .xml, .manifest, .config) and JavaScript (.js).
#
# WHY THIS IS NOT A SIMPLE LINE SCANNER (read before changing anything):
#   1. Comments carrying engineering tags (WORD_01), FreeEDR finding anchors (W1, E9, T2, C1, ...),
#      audit prompts (Prompt N), spec anchors, Sysmon rules or invariant wording are kept.
#   2. PowerShell, C# and XML have distinct syntax; string content is never touched (blank lines
#      inside strings included).
#   3. Every planned file is re-lexed and verified in memory before any write: identical code
#      tokens, byte-identical string/char literals, identical doc comments, identical tag counts.
#      Non-C# files must ALSO pass an independent syntax check before and after the edit:
#      PowerShell = PowerShell's own tokenizer/parser (which also does the lexing),
#      XAML / XML = XML parse + element-tree comparison (tags, attributes and every non-whitespace
#      text byte identical), JS = `node --check`. No checker available = file untouched.
#      A file that fails verification, or that the lexer cannot fully understand, is skipped.
#   4. Writes are refused for files with uncommitted git changes (so `git diff` shows only this
#      tool's edits) unless --allow-dirty is given. BOM (*.ps1 UTF-8 with BOM) and line endings
#      are preserved; files are swapped with ReplaceFileW on Windows so attributes and ACLs survive;
#      hard-linked and read-only files are skipped, never silently changed.
# Default mode prompts before writing. --dry-run never writes, never deletes and never prompts.
