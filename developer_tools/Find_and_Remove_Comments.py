def get_target_files(root_dir, languages):
    extensions = tuple(ext for key in languages for ext in LANGUAGES[key].extensions)
    targets = []
    for current, dirs, files in os.walk(root_dir):
        dirs[:] = sorted((d for d in dirs if d.lower() not in EXCLUDE_FOLDERS), key=str.casefold)
        for file in sorted(files, key=str.casefold):
            name = file.lower()
            if name.endswith(extensions) and not name.endswith(EXCLUDE_FILE_SUFFIXES):
                targets.append(Path(current) / file)
    return targets


def normalized(path):
    return os.path.normcase(os.path.normpath(os.path.abspath(str(path))))


def git_dirty_files(root):
    """Set of normalized absolute paths with uncommitted changes, or None when git is unavailable."""
    def git(*args):
        return subprocess.run(['git', '-C', str(root), *args], capture_output=True, timeout=20, check=True).stdout
    try:
        top = git('rev-parse', '--show-toplevel').decode('utf-8').strip()
        out = git('-c', 'core.quotepath=off', 'status', '--porcelain=v1', '-z', '--untracked-files=all')
    except (OSError, subprocess.SubprocessError, UnicodeError):
        return None
    records = out.decode('utf-8', errors='surrogateescape').split('\0')
    dirty, i = set(), 0
    while i < len(records):
        record = records[i]
        i += 1
        if len(record) < 4:
            continue
        status, rel = record[:2], record[3:]
        dirty.add(normalized(Path(top) / rel))
        if 'R' in status or 'C' in status:
            if i < len(records) and records[i]:
                dirty.add(normalized(Path(top) / records[i]))
            i += 1
    return dirty


def is_read_only(path, st):
    attributes = getattr(st, 'st_file_attributes', 0)
    if attributes & getattr(stat, 'FILE_ATTRIBUTE_READONLY', 0):
        return True
    return not os.access(path, os.W_OK)


def replace_keeping_metadata(path, temp, backup):
    """Puts temp in place of path. Windows: ReplaceFileW keeps the original file's attributes, ACL,
    creation time and streams, and leaves the original bytes in `backup` until this call removes it.
    Elsewhere: permission bits are copied, then os.replace swaps atomically."""
    if os.name != 'nt':
        shutil.copymode(path, temp)
        os.replace(temp, path)
        return
    from ctypes import wintypes
    kernel32 = ctypes.WinDLL('kernel32', use_last_error=True)
    kernel32.ReplaceFileW.argtypes = [wintypes.LPCWSTR, wintypes.LPCWSTR, wintypes.LPCWSTR,
                                      wintypes.DWORD, wintypes.LPVOID, wintypes.LPVOID]
    kernel32.ReplaceFileW.restype = wintypes.BOOL
    if not kernel32.ReplaceFileW(str(path), str(temp), str(backup), 0, None, None):
        err = ctypes.get_last_error()
        if not path.exists() and backup.exists():
            os.replace(backup, path)
        raise OSError(err, 'ReplaceFileW failed: ' + ctypes.FormatError(err).strip())
    backup.unlink()


def write_planned(info):
    """Writes one file; any failure is reported and leaves the original file and the repo as they were."""
    path = info['path']
    temp = path.with_name(path.name + '.freeedr-clean.tmp')
    backup = path.with_name(path.name + '.freeedr-clean.bak')
    created = False
    try:
        st = os.stat(path)
        if path.read_bytes() != ((b'\xef\xbb\xbf' if info['bom'] else b'') + info['text'].encode('utf-8')):
            print(f"{RED}SKIPPED {info['rel']}: file changed since analysis.{RESET}")
            return False
        if st.st_nlink > 1:
            print(f"{RED}SKIPPED {info['rel']}: file has {st.st_nlink} hard links; replacing it would split them.{RESET}")
            return False
        if is_read_only(path, st):
            print(f"{RED}SKIPPED {info['rel']}: file is read-only; clear the attribute yourself if it should change.{RESET}")
            return False
        for leftover in (temp, backup):
            if leftover.exists():
                print(f"{RED}SKIPPED {info['rel']}: leftover file {leftover.name} from an earlier run; "
                      f"check and remove it yourself.{RESET}")
                return False
        with open(temp, 'xb') as handle:
            created = True
            handle.write(info['new_bytes'])
        replace_keeping_metadata(path, temp, backup)
        created = False
    except OSError as exc:
        print(f"{RED}SKIPPED {info['rel']}: could not write ({type(exc).__name__}: {exc}); original kept.{RESET}")
        if created and temp.exists():
            try:
                temp.unlink()
            except OSError:
                print(f"{RED}  Could not remove {temp}; remove it yourself.{RESET}")
        if backup.exists():
            print(f"{RED}  A copy of the original is at {backup}; compare and remove it yourself.{RESET}")
        return False
    if path.read_bytes() != info['new_bytes']:
        print(f"{RED}WRITE VERIFY FAILED: {info['rel']}{RESET}")
        return False
    return True


def print_table(title, data, headers):
    if not data:
        print(f"\n{title}: No issues found.")
        return
    print(f"\n{title}")
    widths = [len(h) for h in headers]
    for row in data:
        for i, val in enumerate(row):
            widths[i] = max(widths[i], len(str(val)))
    widths = [w + 2 for w in widths]
    h_str = " | ".join(f"{h:^{w}}" for h, w in zip(headers, widths))
    print("-" * len(h_str))
    print(h_str)
    print("-" * len(h_str))
    for row in data:
        print(" | ".join(f"{str(val):<{w}}" for val, w in zip(row, widths)))
    print("-" * len(h_str))


def preview(text, limit=60):
    text = text.replace('\t', ' ')
    return (text[:limit] + '..') if len(text) > limit else text


def purge_bytecode_cache(dry_run=False):
    """Removes any __pycache__ / .pyc this tool's folder has accumulated (dry run: only reports them)."""
    tools_dir = Path(__file__).resolve().parent
    found = []
    try:
        for current, dirs, files in os.walk(tools_dir, followlinks=False):
            for name in list(dirs):
                if name == '__pycache__':
                    found.append(Path(current) / name)
                    dirs.remove(name)
            found.extend(Path(current) / f for f in files if f.lower().endswith(('.pyc', '.pyo')))
    except OSError as exc:
        print(f"[!] Could not scan for bytecode cache: {exc}")
        return
    if not found:
        return
    if dry_run:
        print(f"[*] DRY RUN: {len(found)} bytecode cache item(s) found and left in place "
              f"(a normal run removes them): " + ', '.join(str(p.relative_to(tools_dir)) for p in found))
        return
    removed = 0
    for item in found:
        try:
            if item.is_symlink() or not item.is_dir():
                item.unlink()
            else:
                shutil.rmtree(item)
            removed += 1
        except OSError as exc:
            print(f"[!] Could not remove {item}: {exc}")
    print(f"[*] Removed {removed} bytecode cache item(s).")


def main(argv=None):
    parser = argparse.ArgumentParser(description='FreeEDR comment & blank-line cleaner (C#, PowerShell, '
                                                 'XAML/AXAML, XML) with sentinel/tag protection and self-verification.')
    parser.add_argument('--dry-run', action='store_true', help='Analyse and report only; never write, delete or prompt.')
    parser.add_argument('--diff', action='store_true', help='Print a unified diff of every planned edit.')
    parser.add_argument('--show-protected', action='store_true', help='List every kept comment with its reason.')
    parser.add_argument('--root', type=Path, default=DEFAULT_ROOT, help='Repository root (default: parent of developer_tools).')
    parser.add_argument('--only', action='append', default=[], help='Limit to repo-relative glob(s), e.g. "src/Edr.Core/*.cs".')
    parser.add_argument('--languages', default=','.join(LANGUAGES),
                        help=f'Comma-separated subset of: {", ".join(LANGUAGES)} (default: all).')
    parser.add_argument('--allow-dirty', action='store_true', help='Also write files that have uncommitted git changes.')
    parser.add_argument('--yes', action='store_true', help='Skip the Y/N prompt (still honours every safety check).')
    parser.add_argument('--safe', action='store_true',
                        help='Keep explanatory prose; remove only commented-out code, empty comments and extra blank lines. '
                             'Default: remove every unprotected comment (tags/invariants/banners always kept).')
    args = parser.parse_args(argv)
    languages = [l.strip().lower().lstrip('.') for l in args.languages.split(',') if l.strip()]
    unknown = [l for l in languages if l not in LANGUAGES]
    if unknown:
        parser.error(f'unknown language(s): {", ".join(unknown)}')

    for stream in (sys.stdout, sys.stderr):
        try:
            stream.reconfigure(encoding='utf-8', errors='replace')
        except (AttributeError, ValueError):
            pass
    if os.environ.get('NO_COLOR') or not sys.stdout.isatty():
        global RED, GREEN, CYAN, YELLOW, DIM, RESET
        RED = GREEN = CYAN = YELLOW = DIM = RESET = ''
    enable_vt_colors()
    purge_bytecode_cache(args.dry_run)
    root = args.root.resolve()
    if not ((root / 'project_structure.txt').exists() and (root / 'src' / 'Edr.Core').is_dir()):
        print(f"{RED}Not the FreeEDR repository root: {root}{RESET}")
        return 2
    mode = 'SAFE' if args.safe else 'FULL'
    print(f"{CYAN}--- FREEEDR COMMENT CLEANER [{mode} MODE]{' (DRY RUN)' if args.dry_run else ''} ---{RESET}")
    print(f"Target Directory: {root}")
    sentinels = load_sentinels(root)
    files = get_target_files(root, languages)
    if args.only:
        import fnmatch
        files = [f for f in files if any(fnmatch.fnmatchcase(f.relative_to(root).as_posix().lower(), g.lower())
                                         for g in args.only)]
    per_language = Counter(language_for(f).name for f in files)
    print(f"Analyzing {len(files)} files ({', '.join(f'{n} {k}' for k, n in sorted(per_language.items()))}; "
          f"{sum(len(v) for v in sentinels.values())} sentinel tags registered)...")

    plans = [plan_file(f, root, sentinels, aggressive=not args.safe) for f in files]
    junk_data, protected_counter = [], Counter()
    for info in plans:
        for item in info['items']:
            junk_data.append([info['rel'], item['line'], item['type'], preview(item['content'])])
        for p in info['protected']:
            protected_counter[p['reason']] += 1
    skipped = [[i['rel'], i['skip']] for i in plans if i['skip']]
    to_write = [i for i in plans if i['items'] and not i['skip']]

    print("\n" + "=" * 80)
    print(f"{YELLOW}STEP 1: REVIEW COMMENTS & UNNECESSARY EMPTY LINES{RESET}")
    print("=" * 80)
    print_table("TABLE 1: IDENTIFIED JUNK (COMMENTS & EXCESSIVE EMPTY LINES)", junk_data,
                ["File", "Line", "Type", "Content Preview"])
    if protected_counter:
        print(f"\n{GREEN}KEPT (protected) comments: {sum(protected_counter.values())}{RESET}")
        for reason, count in protected_counter.most_common():
            print(f"  {count:5}  {reason}")
    if args.show_protected:
        rows = [[i['rel'], p['line'] if p['line'] == p['end'] else f"{p['line']}-{p['end']}", p['reason'],
                 preview(p['content'])] for i in plans for p in i['protected']]
        print_table("PROTECTED COMMENTS", rows, ["File", "Line(s)", "Reason", "Content Preview"])
    print_table("FILES LEFT UNTOUCHED", skipped, ["File", "Reason"])
    if args.diff:
        for info in to_write:
            print(f"\n{CYAN}{info['rel']}{RESET}")
            for line in difflib.unified_diff(info['text'].splitlines(), info['new_text'].splitlines(),
                                             'a/' + info['rel'], 'b/' + info['rel'], n=1, lineterm=''):
                color = RED if line.startswith('-') and not line.startswith('---') else \
                    GREEN if line.startswith('+') and not line.startswith('+++') else DIM
                print(f"{color}{line}{RESET}")
    print(f"\nAll {len(to_write)} file(s) with planned edits passed self-verification "
          "(identical code tokens, strings, doc comments and tags; syntax re-checked for XML/AXAML/PowerShell).")

    exit_code = 0
    if not to_write:
        print("No comments or unnecessary empty lines to remove.")
    elif args.dry_run:
        print(f"\n{CYAN}DRY RUN: no file was written.{RESET}")
    else:
        dirty = git_dirty_files(root)
        if dirty is None and not args.allow_dirty:
            print(f"{RED}git is unavailable, so edits could not be reviewed/reverted with git. "
                  f"Re-run with --allow-dirty to write anyway.{RESET}")
            return 2
        blocked = [i for i in to_write if dirty and normalized(i['path'].resolve()) in dirty and not args.allow_dirty]
        for info in blocked:
            print(f"{YELLOW}SKIPPED (uncommitted changes, use --allow-dirty): {info['rel']}{RESET}")
        to_write = [i for i in to_write if i not in blocked]
        print(f"\n{YELLOW}WARNING: this permanently edits {len(to_write)} file(s) "
              f"({sum(len(i['items']) for i in to_write)} line(s)). Review with `git diff`.{RESET}")
        try:
            answer = 'Y' if args.yes else input(">>> Do you approve the removal of these comments/empty lines? (Y/N): ").strip().upper()
        except EOFError:
            print(f"\n{YELLOW}No console input available; treated as N. Use --yes for unattended runs.{RESET}")
            answer = 'N'
        if answer == 'Y':
            written = sum(write_planned(info) for info in to_write)
            print(f"\n{GREEN}Cleanup complete: {written}/{len(to_write)} file(s) written.{RESET}")
            if written != len(to_write):
                exit_code = 2
        else:
            print(f"\n{CYAN}Cleanup cancelled by user.{RESET}")

    print("\n" + "=" * 80)
    print(f"{YELLOW}STEP 2: SYSTEM ANALYSIS (SYNTAX & DUPLICATES, REPORT ONLY){RESET}")
    print("=" * 80)
    syntax_data = [[i['rel'], err] for i in plans if (err := check_syntax(i))]
    print_table("TABLE 2: SYNTAX & INDENTATION WARNINGS", syntax_data, ["File", "Issue"])
    all_dupes = [row for i in plans for row in analyze_duplicates(i)]
    print_table("TABLE 3: SCOPE-AWARE DUPLICATES (C#, REPORT ONLY)", all_dupes,
                ["File", "Scope", "Type", "Signature", "Lines"])
    print(f"\n{CYAN}Done.{RESET}")
    purge_bytecode_cache(args.dry_run)
    return exit_code


if __name__ == "__main__":
    sys.exit(main())
